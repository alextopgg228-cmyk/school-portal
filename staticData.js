function sameOptionalNumber(value, expected) {
  return !expected || Number(value) === Number(expected);
}

function sameOptionalText(value, expected) {
  return !expected || String(value) === String(expected);
}

function rowsPayload(rows) {
  return {
    source: 'static',
    warning: 'GitHub Pages показывает статическую копию данных из школьной базы.',
    rows
  };
}

export async function staticApi(path) {
  const url = new URL(path, 'https://github-pages.local');
  const params = url.searchParams;

  if (url.pathname === '/api/health') {
    return {
      mode: 'static',
      error: 'На GitHub Pages нет сервера Node.js и прямого подключения к MS SQL.'
    };
  }

  if (url.pathname === '/api/stats') {
    return { rows: data.stats };
  }

  if (url.pathname === '/api/meta') {
    return { data: data.meta };
  }

  if (url.pathname === '/api/hr') {
    const jobName = params.get('jobName');
    return rowsPayload(data.rows.hr.filter((row) => sameOptionalText(row.JobName, jobName)));
  }

  if (url.pathname === '/api/classes') {
    const studyYear = params.get('studyYear');
    const typeCode = params.get('typeCode');
    return rowsPayload(data.rows.classes
      .filter((row) => sameOptionalNumber(row.StudyYear, studyYear))
      .filter((row) => sameOptionalNumber(row.TypeCode, typeCode)));
  }

  if (url.pathname === '/api/schedule') {
    const classCode = params.get('classCode');
    const scheduleDate = params.get('scheduleDate');
    return rowsPayload(data.rows.schedule
      .filter((row) => sameOptionalNumber(row.ClassCode, classCode))
      .filter((row) => sameOptionalText(row.ScheduleDate, scheduleDate)));
  }

  if (url.pathname === '/api/students') {
    const classCode = params.get('classCode');
    return rowsPayload(data.rows.students.filter((row) => sameOptionalNumber(row.ClassCode, classCode)));
  }

  if (url.pathname === '/api/subjects') {
    const employeeCode = params.get('employeeCode');
    return rowsPayload(data.rows.subjects.filter((row) => sameOptionalNumber(row.EmployeeCode, employeeCode)));
  }

  throw new Error(`Статический сайт не знает запрос: ${url.pathname}`);
}
